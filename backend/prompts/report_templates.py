def knowledge_for(level: str, depth: str = "standard") -> List[str]:
    """返回指定层级、指定深度档的教学要点列表（basic ⊂ standard ⊂ expert 累积）。

    未知层级回落 intermediate，未知深度档回落 standard（与 resolve_params 语义一致）。
    """
    tiers = TEACHING_KNOWLEDGE.get(level, TEACHING_KNOWLEDGE["intermediate"])
    if depth not in KNOWLEDGE_LEVELS:
        depth = "standard"
    out: List[str] = []
    for tier in KNOWLEDGE_LEVELS[: KNOWLEDGE_LEVELS.index(depth) + 1]:
        out.extend(tiers.get(tier, []))
    return out
